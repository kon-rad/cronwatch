#!/usr/bin/env bash
# Convert ios-swift/.env into Cronwatch/Config.xcconfig so Xcode builds
# (Run + Archive from the IDE) pick up the same values as CLI builds.
#
# xcconfig comment marker is // so URLs need https:/$()/host escaping; this
# script handles that automatically.

set -euo pipefail

cd "$(dirname "$0")/.."

ENV_FILE=".env"
OUT_FILE="Cronwatch/Config.xcconfig"

if [[ ! -f "$ENV_FILE" ]]; then
  echo "missing $ENV_FILE — copy .env.example and fill it in" >&2
  exit 1
fi

{
  echo "// Generated by bin/gen-xcconfig.sh from .env. Do not commit."
  echo ""
  while IFS= read -r line || [[ -n "$line" ]]; do
    # Strip comments and blanks.
    [[ "$line" =~ ^[[:space:]]*# ]] && continue
    [[ "$line" =~ ^[[:space:]]*$ ]] && continue

    key="${line%%=*}"
    value="${line#*=}"
    key="$(echo "$key" | tr -d '[:space:]')"
    # Trim leading whitespace from value.
    value="${value#"${value%%[![:space:]]*}"}"
    # xcconfig treats // as a line comment. The official workaround is to
    # interpolate an empty build-setting reference between the slashes so the
    # parser doesn't see // verbatim. Emit literal $() in the file.
    escaped=$(printf '%s' "$value" | sed 's|//|/$()/|g')
    echo "$key = $escaped"
  done < "$ENV_FILE"
} > "$OUT_FILE"

echo "Wrote $OUT_FILE"
